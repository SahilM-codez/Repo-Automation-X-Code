package operators;
	
	public class Comparison_Operator {

		public static void main(String[] args) {
			
			//   > , < , >= , =< , == equal to , != not equal to 
			
			int a = 5;
			int b = 7; 
			boolean c=a>b;  // Greater than 
			System.out.println("the greater than value is -" +c);
					
			boolean f=a<b;   // less than
			System.out.println("the less than value is -"+f);
			
			boolean g=a>=b;   //greater than equal to
			System.out.println("the greater than value is -"+g);
			
			boolean l=a<=b; // smaller than equal to
			System.out.println("the less than value is -"+l);
			
			
			boolean j=a==b; // equal to 
			System.out.println("the equal to value is -"+j);
		
			boolean n=a!=b; // not equal to
			System.out.println("the not equal to value is -"+n);
			
			
		} 



	

}
